export function translateZhTW(
  key: string,
  defaultValue: string,
  interpolations: Record<string, unknown> = {},
): string {
  let value = zhTW[key] ?? defaultValue;
  for (const [k, v] of Object.entries(interpolations)) {
    value = value.replaceAll(`{{${k}}}`, String(v));
  }
  return value;
}
